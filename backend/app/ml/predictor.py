"""
Prediction engine.

Provides two prediction strategies:
  1. Rule-based weighted scorer (fallback / default)
  2. Trained ML model (when loaded via ModelManager)

The public function `generate_prediction` automatically selects the
appropriate strategy based on model availability.
"""

from __future__ import annotations

from app.core.config import settings
from app.core.constants import (
    RISK_HIGH,
    RISK_LOW,
    RISK_MODERATE,
    WEIGHT_CONFLICT,
    WEIGHT_DENSITY,
    WEIGHT_IDP_CAMP,
    WEIGHT_POPULATION,
    WEIGHT_RAINFALL,
    WEIGHT_SEASON,
    WEIGHT_WASH,
)
from app.core.logger import logger
from app.ml.model_loader import model_manager
from app.ml.preprocessing import build_feature_vector, build_model_input
from app.models.request_models import PredictionRequest
from app.models.response_models import PredictionResponse


def generate_prediction(request: PredictionRequest) -> PredictionResponse:
    """
    Generate a cholera outbreak risk prediction.

    Uses the trained ML model when available; otherwise falls back
    to a deterministic rule-based scorer.
    """
    if model_manager.is_loaded:
        return _predict_with_model(request)
    return _predict_rule_based(request)


# ── Rule-based predictor ─────────────────────────────────────────────────

def _predict_rule_based(request: PredictionRequest) -> PredictionResponse:
    """Weighted-sum risk scorer using normalised features."""
    features = build_feature_vector(request)

    risk_score = (
        WEIGHT_RAINFALL * features["rainfall_norm"]
        + WEIGHT_WASH * features["wash_deficit"]
        + WEIGHT_CONFLICT * features["conflict_score"]
        + WEIGHT_DENSITY * features["density_norm"]
        + WEIGHT_POPULATION * features["population_norm"]
        + WEIGHT_IDP_CAMP * features["idp_camp"]
        + WEIGHT_SEASON * features["peak_season"]
    )
    probability = round(min(risk_score, 1.0), 3)
    risk_level = _classify_risk(probability)

    logger.info(
        "Rule-based prediction for %s: probability=%.3f, risk=%s",
        request.location,
        probability,
        risk_level,
    )

    return PredictionResponse(
        location=request.location,
        risk_level=risk_level,
        probability=probability,
        confidence=round(1.0 - abs(probability - 0.5) * 0.4, 3),
        model_version=settings.APP_VERSION,
        prediction_method="rule-based",
        contributing_factors=_build_factors(features),
        explanation=(
            "Risk score combines rainfall, sanitation conditions, conflict pressure, "
            "population density, IDP camp presence, and seasonal patterns to estimate "
            "outbreak likelihood."
        ),
    )


# ── ML model predictor ──────────────────────────────────────────────────

def _predict_with_model(request: PredictionRequest) -> PredictionResponse:
    """Use the trained sklearn model for prediction."""
    model = model_manager.model
    X = build_model_input(request)

    try:
        # Attempt probability prediction first
        if hasattr(model, "predict_proba"):
            proba = model.predict_proba(X)
            probability = round(float(proba[0][1]), 3)
        else:
            prediction = model.predict(X)
            probability = round(float(prediction[0]), 3)

        risk_level = _classify_risk(probability)
        features = build_feature_vector(request)

        logger.info(
            "ML model prediction for %s: probability=%.3f, risk=%s",
            request.location,
            probability,
            risk_level,
        )

        return PredictionResponse(
            location=request.location,
            risk_level=risk_level,
            probability=probability,
            confidence=round(1.0 - abs(probability - 0.5) * 0.3, 3),
            model_version=settings.APP_VERSION,
            prediction_method="ml-model",
            contributing_factors=_build_factors(features),
            explanation=(
                "Prediction generated by the trained machine-learning model using "
                "environmental, demographic, and conflict indicators."
            ),
        )
    except Exception as exc:
        logger.error("ML model prediction failed, falling back: %s", exc)
        return _predict_rule_based(request)


# ── Helpers ──────────────────────────────────────────────────────────────

def _classify_risk(probability: float) -> str:
    """Map a probability value to a risk level string."""
    if probability >= settings.HIGH_RISK_THRESHOLD:
        return RISK_HIGH
    if probability >= settings.MODERATE_RISK_THRESHOLD:
        return RISK_MODERATE
    return RISK_LOW


def _build_factors(features: dict[str, float]) -> list[dict[str, object]]:
    """Build a human-readable list of contributing factors."""
    labels = {
        "rainfall_norm": "Rainfall intensity",
        "wash_deficit": "Poor sanitation (WASH deficit)",
        "conflict_score": "Conflict / insurgency pressure",
        "density_norm": "Population density",
        "population_norm": "Total population",
        "idp_camp": "IDP camp presence",
        "peak_season": "Peak rainy season",
    }
    factors = []
    for key, value in features.items():
        factors.append({
            "factor": labels.get(key, key),
            "value": round(value, 3),
            "impact": "high" if value >= 0.7 else ("moderate" if value >= 0.4 else "low"),
        })
    return sorted(factors, key=lambda f: f["value"], reverse=True)